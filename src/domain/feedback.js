/**
 * Комментарий-заголовок в зависимости от итогового балла.
 */
function getSummaryComment(stars) {
  if (stars >= 5) return 'Превосходно! Именно такой интерьер я и представлял(а).';
  if (stars === 4) return 'Очень хорошо! Осталось совсем немного до идеала.';
  if (stars === 3) return 'Неплохо, но есть над чем поработать.';
  if (stars === 2) return 'Пока не то, что я ожидал(а). Попробуйте пересмотреть подход.';
  return 'К сожалению, этот интерьер совсем не соответствует заданию.';
}

/**
 * Выбирает один комментарий из массива (детерминированно, по индексу нарушения).
 */
function pickComment(comments, index) {
  if (!comments || comments.length === 0) return null;
  return comments[index % comments.length];
}

/**
 * Главная функция: генерирует список комментариев на основе результата оценки.
 * @param {object} result - результат evaluateRoom()
 * @returns {Array<{text:string, category:string, severity:number}>}
 */
export function generateFeedback(result) {
  const feedback = [];
  const { violations, groupScores } = result;

  // --- Комментарии по нарушениям стиля ---
  const styleViolations = violations.filter(v => v.type === 'style');
  for (const v of styleViolations) {
    const key = `${v.feature}:${v.operator}`;
    const candidates = STYLE_FEEDBACK[key];
    const comment = pickComment(candidates, v.deficit ? Math.floor(v.deficit * 10) : 0);
    if (comment) {
      feedback.push({
        text: comment.text,
        category: v.group || 'Стиль',
        severity: comment.severity,
        feature: v.feature,
      });
    }
  }

  // --- Комментарии по эргономике ---
  const ergoViolations = violations.filter(v => v.type === 'ergonomics');
  for (const v of ergoViolations) {
    const candidates = ERGO_FEEDBACK[v.rule];
    const comment = pickComment(candidates, feedback.length);
    if (comment) {
      feedback.push({
        text: comment.text,
        category: 'Эргономика',
        severity: comment.severity,
        rule: v.rule,
      });
    }
  }

  // --- Позитивные комментарии по группам без нарушений ---
  for (const [group, score] of Object.entries(groupScores)) {
    if (score >= 0.9) {
      const candidates = POSITIVE_FEEDBACK[group];
      const comment = pickComment(candidates, feedback.length);
      if (comment) {
        feedback.push({
          text: comment,
          category: group,
          severity: 0, // позитив
        });
      }
    }
  }

  // --- Сортировка: сначала критичные, потом средние, потом позитивные ---
  feedback.sort((a, b) => b.severity - a.severity);

  return feedback;
}

/**
 * Возвращает итоговый комментарий-заголовок.
 * @param {number} stars - итоговые звёзды (1-5)
 * @returns {string}
 */
export function getSummary(stars) {
  return getSummaryComment(stars);
}

/**
 * Возвращает топ-N самых критичных комментариев (для краткого отображения).
 * @param {Array} feedback - результат generateFeedback()
 * @param {number} n - количество
 * @returns {Array}
 */
export function getTopFeedback(feedback, n = 3) {
  return feedback.filter(f => f.severity > 0).slice(0, n);
}